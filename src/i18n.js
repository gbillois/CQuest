export function getLocale() {
  return locale;
}

export function t(key, vars = {}) {
  const dict = MESSAGES[locale] || MESSAGES.en;
  let out = dict[key] || MESSAGES.en[key] || key;
  for (const [k, v] of Object.entries(vars)) {
    out = out.replaceAll(`{${k}}`, String(v));
  }
  return out;
}
